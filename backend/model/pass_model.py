class Passenger:
    def __init__(
        self,
        id: int,
        name: str,
        phone: str,
        busNo: str,
        email: str,
        age: int,
        gender: str,
        seatNo: int
    ):
        self.id = id
        self.name = name
        self.phone = phone
        self.busNo = busNo
        self.email = email
        self.age = age
        self.gender = gender
        self.seatNo = seatNo